import AppKit
import Carbon.HIToolbox

/// Inserts text into whichever app has focus: put it on the pasteboard, post ⌘V,
/// then restore the user's previous pasteboard contents.
enum TextInserter {
    /// Stamped on events we post so our own keyboard monitor ignores them.
    static let syntheticMarker: Int64 = 0x4D52_4D52 // "MRMR"

    /// Key code that types "v" in the current ASCII-capable layout (Dvorak, AZERTY, …).
    /// Cached; refreshed when the keyboard layout changes (see `observeLayoutChanges`).
    nonisolated(unsafe) private(set) static var pasteKeyCode: CGKeyCode = CGKeyCode(kVK_ANSI_V)

    @MainActor
    static func observeLayoutChanges() {
        refreshPasteKeyCode()
        DistributedNotificationCenter.default().addObserver(
            forName: NSNotification.Name(kTISNotifySelectedKeyboardInputSourceChanged as String),
            object: nil, queue: .main
        ) { _ in
            MainActor.assumeIsolated { refreshPasteKeyCode() }
        }
    }

    @MainActor
    private static func refreshPasteKeyCode() {
        pasteKeyCode = keyCode(forCharacter: "v") ?? CGKeyCode(kVK_ANSI_V)
    }

    @MainActor
    static func insert(_ text: String) {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Ask clipboard managers not to record this temporary entry.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChangeCount = pasteboard.changeCount

        postShortcut(keyCode: pasteKeyCode, flags: .maskCommand)

        // Electron apps can read the pasteboard a little late, so wait before restoring it.
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.0) {
            // Leave the pasteboard alone if something else wrote to it meanwhile.
            guard pasteboard.changeCount == ourChangeCount else { return }
            restore(saved, to: pasteboard)
        }
    }

    /// Undoes the last paste (⌘Z) and inserts a replacement, used by "undo AI edits".
    @MainActor
    static func replaceLastInsertion(with text: String) {
        postShortcut(keyCode: keyCode(forCharacter: "z") ?? CGKeyCode(kVK_ANSI_Z), flags: .maskCommand)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { insert(text) }
    }

    @MainActor
    static func copyToPasteboard(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    static func snapshot(_ pasteboard: NSPasteboard) -> [[(NSPasteboard.PasteboardType, Data)]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    static func restore(_ saved: [[(NSPasteboard.PasteboardType, Data)]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let items = saved.map { pairs in
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }

    static func postShortcut(keyCode: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: keyDown) else { continue }
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: syntheticMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    static func keyCode(forCharacter character: String) -> CGKeyCode? {
        guard let source = TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue(),
              let layoutPointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }
        let layoutData = Unmanaged<CFData>.fromOpaque(layoutPointer).takeUnretainedValue() as Data
        return layoutData.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            for code in 0..<128 {
                var deadKeyState: UInt32 = 0
                var chars = [UniChar](repeating: 0, count: 4)
                var length = 0
                let status = UCKeyTranslate(
                    layout, UInt16(code), UInt16(kUCKeyActionDisplay), 0, UInt32(LMGetKbdType()),
                    OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeyState, chars.count, &length, &chars
                )
                if status == noErr, length > 0, String(utf16CodeUnits: chars, count: length) == character {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }
}
